#!/usr/bin/env python3
"""
build_tracker.py — regenerate the Published Papers section of the white paper tracker
directly from white-papers/manifest.json (the count of record), preserving every
hand-maintained byte outside that section (forthcoming table, engagement log, notes).

Owner rules honored:
- The manifest is the only count of record; the tracker must never fall behind it again.
- Series placement is the owner's call: papers not present in SERIES_MAP land under
  'Added by records sync — placement pending' and are moved by editing SERIES_MAP.
- Append-only: nothing outside the Published Papers section is touched.

Usage:  python3 tools/records/build_tracker.py [--root REPO_ROOT]
"""
import argparse
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

TRACKER = Path("white-papers/white-paper-tracker.md")
MANIFEST = Path("white-papers/manifest.json")

# id -> series heading (owner-maintained; new papers default to placement-pending)
SERIES_MAP = {
    "chatgpt-case-study": "Series I — Platform Dependency",
    "aws-case-study": "Series I — Platform Dependency",
    "aisha-case-study": "Series I — Platform Dependency",
    "manus-case-study": "Series I — Platform Dependency",
    "google-case-study": "Series I — Platform Dependency",
    "deepseek-case-study": "Series I — Platform Dependency",
    "the-cache-is-not-the-corpus": "Series I — Platform Dependency",
    "the-ai-cartel-and-the-sovereign-response": "Series II — Containment & Governance",
    "it-scaled-the-fence": "Series II — Containment & Governance",
    "samaritan-is-here": "Series II — Containment & Governance",
    "sovereign-recursive-improvement": "Series II — Containment & Governance",
    "who-tests-the-testers": "Series II — Containment & Governance",
    "tourist-to-student": "Series III — Practice & Method",
    "white-paper-methodology": "Series III — Practice & Method",
    "methodology": "Series III — Practice & Method",
    "sovereign-ai-vs-silicon-valley": "Series III — Practice & Method",
    "three-days-of-silence": "Series III — Practice & Method",
    "the-missing-link": "Series III — Practice & Method",
}
INFRA_IDS = {"record-changelog", "White_Paper_AI_Collaboration_Case_Study"}  # changelog + redirect
RETIRED_IDS = {"comparative"}

SERIES_ORDER = [
    "Series I — Platform Dependency",
    "Series II — Containment & Governance",
    "Series III — Practice & Method",
    "Series placement pending (added by records sync)",
]

SECTION_RE = re.compile(r"(^## Published Papers[^\n]*\n)(.*?)(?=^## )", re.M | re.S)


def esc(s: str) -> str:
    return s.replace("|", "\\|")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=".")
    args = ap.parse_args()
    root = Path(args.root).resolve()
    tpath = root / TRACKER
    tracker = tpath.read_text(encoding="utf-8")
    papers = json.loads((root / MANIFEST).read_text(encoding="utf-8"))["white_papers"]

    active = [p for p in papers
              if p["id"] not in INFRA_IDS and p["id"] not in RETIRED_IDS]
    retired = [p for p in papers if p["id"] in RETIRED_IDS]

    def sort_key(p):
        return (p.get("date") or p.get("timestamp") or "", p.get("timestamp") or "")

    grouped = {name: [] for name in SERIES_ORDER}
    for p in sorted(active, key=sort_key):
        series = SERIES_MAP.get(p["id"])
        if series is None:
            grouped["Series placement pending (added by records sync)"].append(p)
        else:
            grouped.setdefault(series, []).append(p)

    out = []
    out.append(f"## Published Papers — {len(active)} active in the manifest, "
               f"{len(SERIES_ORDER) - 1} series, auto-synced from manifest.json")
    out.append("<!-- RECORDS-AUTO:BEGIN published — regenerated by tools/records/build_tracker.py; "
               "edit SERIES_MAP there to place new papers, or move rows by hand in the tracker (next sync keeps hand moves only if SERIES_MAP updated) -->")
    for series in SERIES_ORDER:
        rows = grouped.get(series, [])
        if not rows:
            continue
        out.append(f"### {series} ({len(rows)})")
        out.append("| # | Paper | Published |")
        out.append("| --- | --- | --- |")
        for i, p in enumerate(rows, 1):
            date = p.get("date") or p.get("timestamp") or "—"
            out.append(f"| {i} | [{esc(p['title'])}]({p['permalink']}) | {date} |")
        out.append("")
    if retired:
        out.append(f"### Retired ({len(retired)})")
        out.append("| Paper | Status |")
        out.append("| --- | --- |")
        for p in retired:
            out.append(f"| [{esc(p['title'])}]({p['permalink']}) | Superseded 2026-10-07 (owner record) |")
        out.append("")
    out.append("<!-- RECORDS-AUTO:END -->")
    out.append("")

    new_section = "\n".join(out) + "\n"
    m = SECTION_RE.search(tracker)
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    if m:
        tracker_new = tracker[:m.start()] + new_section + tracker[m.end():]
        action = "Published Papers section regenerated"
    else:
        marker = "\n## Forthcoming"
        if marker in tracker:
            tracker_new = tracker.replace(marker, "\n" + new_section + marker, 1)
            action = "Published Papers section inserted before Forthcoming"
        else:
            tracker_new = tracker.rstrip() + "\n\n" + new_section
            action = "Published Papers section appended (no Forthcoming marker found)"
    tpath.write_text(tracker_new, encoding="utf-8")

    print(f"{action}: {len(active)} active papers from manifest, {stamp}")
    pending = grouped.get("Series placement pending (added by records sync)", [])
    if pending:
        print("PLACEMENT PENDING (edit SERIES_MAP in build_tracker.py): "
              + ", ".join(p["id"] for p in pending))
    return 0


if __name__ == "__main__":
    sys.exit(main())
